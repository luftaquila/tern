"""Generate WcWidthTables.kt from the Unicode Character Database.

Usage:
    gen_wcwidth.py <EastAsianWidth.txt> <DerivedGeneralCategory.txt> <output.kt>

Both input files come from https://www.unicode.org/Public/<version>/ucd/
(DerivedGeneralCategory.txt lives in the extracted/ subdirectory).

Rules (mirroring glibc's wcwidth tables, which is what remote programs use):
  * width 0: General_Category Mn, Me, Cf (except U+00AD SOFT HYPHEN),
             U+200B, Hangul Jungseong/Jongseong U+1160..U+11FF and U+D7B0..U+D7FF.
             (C0/C1 controls are handled in code.)
  * width 2: East_Asian_Width W or F, including the unassigned code points that
             the EastAsianWidth.txt header says default to W.
  * width 1: everything else.
Zero width takes precedence over wide (e.g. U+302A..U+302D, U+3099..U+309A).
"""
import re
import sys

MAX = 0x110000

# Default "W" ranges for code points not listed explicitly (EastAsianWidth.txt header).
DEFAULT_WIDE = [
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
    (0x20000, 0x2FFFD),
    (0x30000, 0x3FFFD),
]

LINE = re.compile(r'^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)')


def parse(path):
    out = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            m = LINE.match(line)
            if not m:
                continue
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            out.append((lo, hi, m.group(3)))
    return out


def ranges(flags):
    res = []
    start = None
    for cp in range(MAX):
        if flags[cp]:
            if start is None:
                start = cp
        elif start is not None:
            res.append((start, cp - 1))
            start = None
    if start is not None:
        res.append((start, MAX - 1))
    return res


def emit(name, rs):
    lines = [f'    val {name}: IntArray = intArrayOf(']
    row = []
    for lo, hi in rs:
        row.append(f'0x{lo:X}, 0x{hi:X}')
        if len(row) == 4:
            lines.append('        ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('        ' + ', '.join(row) + ',')
    lines.append('    )')
    return '\n'.join(lines)


def main():
    eaw_path, gc_path, out_path = sys.argv[1:4]
    eaw = ['N'] * MAX
    for lo, hi in DEFAULT_WIDE:
        for cp in range(lo, hi + 1):
            eaw[cp] = 'W'
    for lo, hi, v in parse(eaw_path):
        for cp in range(lo, hi + 1):
            eaw[cp] = v

    zero = [False] * MAX
    for lo, hi, cat in parse(gc_path):
        if cat in ('Mn', 'Me', 'Cf'):
            for cp in range(lo, hi + 1):
                zero[cp] = True
    zero[0x00AD] = False
    zero[0x200B] = True
    for cp in list(range(0x1160, 0x1200)) + list(range(0xD7B0, 0xD800)):
        zero[cp] = True

    wide = [(eaw[cp] in ('W', 'F')) and not zero[cp] for cp in range(MAX)]

    with open(eaw_path, encoding='utf-8') as f:
        header = f.readline().strip().lstrip('# ')

    zr = ranges(zero)
    wr = ranges(wide)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('// Copyright (C) 2026 luftaquila\n')
        f.write('// SPDX-License-Identifier: GPL-3.0-only\n')
        f.write('// Additional terms under GPL section 7 apply; see NOTICE.\n\n')
        f.write('// GENERATED by terminal/tools/gen_wcwidth.py from ' + header + '\n')
        f.write('// and DerivedGeneralCategory.txt of the same Unicode version. Do not edit by hand.\n')
        f.write('package io.github.luftaquila.tern.terminal\n\n')
        f.write('/** Sorted inclusive [start, end] pairs. */\n')
        f.write('internal object WcWidthTables {\n')
        f.write(emit('ZERO_WIDTH', zr) + '\n\n')
        f.write(emit('WIDE', wr) + '\n')
        f.write('}\n')
    print(f'zero-width ranges: {len(zr)}, wide ranges: {len(wr)}', file=sys.stderr)


if __name__ == '__main__':
    main()
