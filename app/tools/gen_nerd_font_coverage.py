"""Generates NerdFontCoverage.kt (code point ranges of the bundled Symbols Nerd Font).

Usage: python3 -I gen_nerd_font_coverage.py <SymbolsNerdFont-Regular.ttf> <output.kt>
Requires fontTools (pip install fonttools).
"""
import sys
from fontTools.ttLib import TTFont

font_path, out_path = sys.argv[1], sys.argv[2]
cps = sorted(TTFont(font_path).getBestCmap())
ranges = []
start = prev = cps[0]
for cp in cps[1:]:
    if cp != prev + 1:
        ranges.append((start, prev))
        start = cp
    prev = cp
ranges.append((start, prev))

lines = ",\n".join(f"        0x{a:X}, 0x{b:X}" for a, b in ranges)
out = f"""// Copyright (C) 2026 luftaquila
// SPDX-License-Identifier: GPL-3.0-only
// Additional terms under GPL section 7 apply; see NOTICE.

package io.github.luftaquila.tern.termview

// GENERATED by app/tools/gen_nerd_font_coverage.py from SymbolsNerdFont-Regular.ttf
// (Nerd Fonts v3.5.1). Do not edit by hand.

/** Code points covered by the bundled Symbols Nerd Font. */
internal object NerdFontCoverage {{
    /** Sorted inclusive [start, end] pairs. */
    private val RANGES = intArrayOf(
{lines},
    )

    fun covers(cp: Int): Boolean {{
        var lo = 0
        var hi = RANGES.size / 2 - 1
        while (lo <= hi) {{
            val mid = (lo + hi) ushr 1
            when {{
                cp < RANGES[mid * 2] -> hi = mid - 1
                cp > RANGES[mid * 2 + 1] -> lo = mid + 1
                else -> return true
            }}
        }}
        return false
    }}

    /** Unicode private use areas, where Nerd Font icons live. */
    fun isPrivateUse(cp: Int): Boolean = cp in 0xE000..0xF8FF || cp in 0xF0000..0xFFFFD || cp in 0x100000..0x10FFFD
}}
"""
open(out_path, "w").write(out)
print(f"{len(ranges)} ranges, {len(cps)} code points")
